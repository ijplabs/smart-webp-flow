<?php
/**
 * Dynamic Post Content Image Filter Service.
 *
 * @package SmartWebPFlow\Services
 */

namespace SmartWebPFlow\Services;

use SmartWebPFlow\Common\Constants;

// Exit if accessed directly.
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Class PostContentService
 * Safely replaces JPEG and PNG URLs with WebP equivalents on-the-fly in frontend output.
 */
class PostContentService {

	/**
	 * In-memory cache for disk existence checks to optimize performance.
	 *
	 * @var array<string, bool>
	 */
	private static $existence_cache = array();

	/**
	 * Cached upload directory information.
	 *
	 * @var array<string, string>|null
	 */
	private static $upload_dir = null;

	/**
	 * Registers WordPress content filters.
	 *
	 * @return void
	 */
	public function register_hooks(): void {
		// Non-destructive frontend dynamic content filter.
		add_filter( 'the_content', array( $this, 'filter_content' ), 99 );

		// Core image tag filter (WP 5.5+).
		add_filter( 'wp_content_img_tag', array( $this, 'filter_content_img_tag' ), 99, 3 );
	}

	/**
	 * Filters the post content on the frontend.
	 *
	 * @param string $content Post HTML content.
	 * @return string Filtered HTML content.
	 */
	public function filter_content( string $content ): string {
		// Skip empty content.
		if ( empty( $content ) ) {
			return $content;
		}

		// Check if dynamic frontend filter is enabled in settings.
		$settings = get_option( Constants::OPTION_SETTINGS, array() );
		if ( isset( $settings['dynamic_filter'] ) && empty( $settings['dynamic_filter'] ) ) {
			return $content;
		}

		// Skip admin or feed contexts.
		if ( ( function_exists( 'is_admin' ) && is_admin() ) || ( function_exists( 'is_feed' ) && is_feed() ) ) {
			return $content;
		}

		return $this->replace_image_urls( $content );
	}

	/**
	 * Filters individual image tags generated by WordPress.
	 *
	 * @param string $filtered_image Complete HTML img tag.
	 * @param string $context        Context string.
	 * @param int    $attachment_id  Attachment ID.
	 * @return string Filtered img tag.
	 */
	public function filter_content_img_tag( string $filtered_image, string $context, int $attachment_id ): string {
		unset( $context, $attachment_id );

		if ( empty( $filtered_image ) ) {
			return $filtered_image;
		}

		$settings = get_option( Constants::OPTION_SETTINGS, array() );
		if ( isset( $settings['dynamic_filter'] ) && empty( $settings['dynamic_filter'] ) ) {
			return $filtered_image;
		}

		return $this->replace_image_urls( $filtered_image );
	}

	/**
	 * Scans HTML content for img tags and safely replaces JPG/PNG URLs with WebP URLs.
	 *
	 * @param string $html HTML string.
	 * @return string Modified HTML string with WebP URLs.
	 */
	public function replace_image_urls( string $html ): string {
		// Quick check before expensive regex: Does content contain jpg or png?
		if ( ! preg_match( '/\.(jpe?g|png)/i', $html ) ) {
			return $html;
		}

		// 1. Process <img> tags.
		$pattern = '/<img\b([^>]*)>/i';

		return (string) preg_replace_callback(
			$pattern,
			function ( $matches ) {
				$img_attrs = $matches[1];

				// Replace src attribute.
				$img_attrs = preg_replace_callback(
					'/\bsrc=(["\'])(https?:\/\/[^\s"\']+\.(?:jpe?g|png))(?:\?[^\s"\']*)?\1/i',
					function ( $src_match ) {
						$quote = $src_match[1];
						$url   = $src_match[2];

						if ( $this->webp_exists_for_url( $url ) ) {
							$webp_url = (string) preg_replace( '/\.(jpe?g|png)$/i', '.webp', $url );
							return 'src=' . $quote . $webp_url . $quote;
						}

						return $src_match[0];
					},
					$img_attrs
				);

				// Replace srcset attribute if present.
				$img_attrs = preg_replace_callback(
					'/\bsrcset=(["\'])([^"\']+)\1/i',
					function ( $srcset_match ) {
						$quote  = $srcset_match[1];
						$srcset = $srcset_match[2];

						$updated_srcset = $this->replace_srcset_urls( $srcset );
						return 'srcset=' . $quote . $updated_srcset . $quote;
					},
					$img_attrs
				);

				return '<img' . $img_attrs . '>';
			},
			$html
		);
	}

	/**
	 * Replaces URLs within a srcset attribute string.
	 *
	 * @param string $srcset Raw srcset string (e.g. "url1 100w, url2 200w").
	 * @return string Modified srcset string.
	 */
	public function replace_srcset_urls( string $srcset ): string {
		$sources = explode( ',', $srcset );
		$updated = array();

		foreach ( $sources as $part ) {
			$part = trim( $part );
			if ( empty( $part ) ) {
				continue;
			}

			$segments = preg_split( '/\s+/', $part, 2 );
			if ( ! empty( $segments[0] ) ) {
				$url        = $segments[0];
				$descriptor = isset( $segments[1] ) ? ' ' . $segments[1] : '';

				if ( preg_match( '/\.(jpe?g|png)$/i', $url ) && $this->webp_exists_for_url( $url ) ) {
					$webp_url  = (string) preg_replace( '/\.(jpe?g|png)$/i', '.webp', $url );
					$updated[] = $webp_url . $descriptor;
					continue;
				}
			}

			$updated[] = $part;
		}

		return implode( ', ', $updated );
	}

	/**
	 * Checks whether a corresponding .webp file exists on the local filesystem for a given URL.
	 *
	 * @param string $image_url Full URL of the image.
	 * @return bool True if physical .webp exists on disk, false otherwise.
	 */
	public function webp_exists_for_url( string $image_url ): bool {
		$local_path = $this->url_to_local_path( $image_url );
		if ( empty( $local_path ) ) {
			return false;
		}

		$webp_path = (string) preg_replace( '/\.(jpe?g|png)$/i', '.webp', $local_path );

		if ( isset( self::$existence_cache[ $webp_path ] ) ) {
			return self::$existence_cache[ $webp_path ];
		}

		$exists                              = file_exists( $webp_path );
		self::$existence_cache[ $webp_path ] = $exists;

		return $exists;
	}

	/**
	 * Resolves a public image URL to its local server filesystem path.
	 *
	 * @param string $image_url Public image URL.
	 * @return string|null Absolute filesystem path, or null if outside upload dir.
	 */
	public function url_to_local_path( string $image_url ): ?string {
		if ( null === self::$upload_dir ) {
			self::$upload_dir = function_exists( 'wp_upload_dir' ) ? wp_upload_dir() : array();
		}

		$baseurl = self::$upload_dir['baseurl'] ?? '';
		$basedir = self::$upload_dir['basedir'] ?? '';

		if ( empty( $baseurl ) || empty( $basedir ) ) {
			return null;
		}

		// Normalize protocols for matching (http vs https).
		$norm_url     = preg_replace( '/^https?:/i', '', $image_url );
		$norm_baseurl = preg_replace( '/^https?:/i', '', $baseurl );

		if ( null !== $norm_url && null !== $norm_baseurl && str_starts_with( $norm_url, $norm_baseurl ) ) {
			$relative = substr( $norm_url, strlen( $norm_baseurl ) );
			return $basedir . $relative;
		}

		return null;
	}

	/**
	 * Clears the in-memory file existence cache.
	 *
	 * @return void
	 */
	public static function clear_cache(): void {
		self::$existence_cache = array();
		self::$upload_dir      = null;
	}
}
